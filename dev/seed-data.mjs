// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log('🌱 Seeding data...\n');

  // ── Courses ──
  const allCourses = [
    ...CSE_COURSES.map(c => ({ ...c, department: 'CSE' })),
    ...EEE_COURSES.map(c => ({ ...c, department: 'EEE' })),
    ...ME_COURSES.map(c => ({ ...c, department: 'ME' })),
    ...CE_COURSES.map(c => ({ ...c, department: 'CE' })),
    ...IPE_COURSES.map(c => ({ ...c, department: 'IPE' })),
    ...TE_COURSES.map(c => ({ ...c, department: 'TE' })),
  ];

  let courseCount = 0;
  for (const c of allCourses) {
    await prisma.course.upsert({
      where: { code: c.code },
      create: c,
      update: { name: c.name, credit: c.credit, department: c.department },
    });
    courseCount++;
  }
  console.log(`✅ Courses: ${courseCount} upserted`);

  // ── Campus Locations ──
  let locCount = 0;
  for (const floor of campusFloors) {
    for (const room of floor.rooms) {
      // Determine hotspot data: room may have `hotspot`, `hotspots`, or just `x`/`y`
      let hotspotData = '{}';
      let x = room.x ?? null;
      let y = room.y ?? null;

      if (room.hotspot) {
        hotspotData = JSON.stringify(room.hotspot);
      } else if (room.hotspots) {
        hotspotData = JSON.stringify(room.hotspots);
      }

      await prisma.campusLocation.upsert({
        where: { id: locCount + 1 }, // approximate — we'll use create instead
        create: {
          floor: floor.floor,
          roomId: room.id,
          name: room.name,
          type: room.type,
          hotspotData,
          x,
          y,
          mapImage: floor.mapImage || '',
        },
        update: {
          name: room.name,
          type: room.type,
          hotspotData,
          x,
          y,
          mapImage: floor.mapImage || '',
        },
      });
      locCount++;
    }
  }
  console.log(`✅ Campus Locations: ${locCount} upserted`);

  console.log('\n🎉 Seed complete!');
}

main()
  .catch((err) => {
    console.error('❌ Seed failed:', err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
