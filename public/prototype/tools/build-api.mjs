// Builds docs/d-api-data.js by scanning server/*.mjs for /api routes and their HTTP methods.
// Run: node public/prototype/tools/build-api.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const files = [...fs.readdirSync(path.join(root, 'server')).filter((f) => f.endsWith('.mjs') && !f.includes('.test.')).map((f) => 'server/' + f),
  ...fs.readdirSync(path.join(root, 'server/gaming')).filter((f) => f.endsWith('.mjs') && !f.includes('.test.')).map((f) => 'server/gaming/' + f)];

const found = new Map(); const desc = new Map();
for (const f of files) {
  const lines = fs.readFileSync(path.join(root, f), 'utf8').split('\n');
  lines.forEach((l, i) => {
    const cat = l.match(/\[\s*'(GET|POST|PUT|PATCH|DELETE)',\s*'(\/api\/[^']+)',\s*'([^']+)'\s*\]/);
    if (cat) { desc.set(cat[1] + ' ' + cat[2], cat[3]); return; }
    if (!/req\.url|pathname|url\s*===|startsWith|match\(|route\(|path\s*===/.test(l)) return;
    for (const m of l.matchAll(/['"`](\/api\/[A-Za-z0-9_\-/:.]+)['"`]/g)) {
      let p = m[1].replace(/\/$/, '/:id'); if (p.includes('/api/dev')) continue;
      if (/startsWith\(['"`]\/api\/[^'"`]+\/['"`]\)/.test(l) && !p.endsWith(':id')) p += '/:id';
      const ctx = l + (lines[i + 1] || ''); const ms = [...ctx.matchAll(/method\s*===\s*['"](GET|POST|PUT|PATCH|DELETE)['"]/g)].map((x) => x[1]);
      const key = (ms[0] || 'ANY') + ' ' + p;
      if (!found.has(key)) found.set(key, { m: ms[0] || 'ANY', p, file: f });
    }
  });
}
for (const k of desc.keys()) if (!found.has(k)) { const [m, p] = k.split(' '); found.set(k, { m, p, file: 'server/dev.mjs' }); }
// Gaming has its own table: ['GET', '/rooms/:id', handler] mounted at /api/gaming.
for (const l of fs.readFileSync(path.join(root, 'server/gaming/gamingRoutes.mjs'), 'utf8').split('\n')) { const g = l.match(/^\s*\['(GET|POST|PUT|PATCH|DELETE)',\s*'(\/[^']*)',.*svc\.(\w+)/); if (g) { const p = '/api/gaming' + g[2]; found.set(g[1] + ' ' + p, { m: g[1], p, file: 'server/gaming/gamingRoutes.mjs' }); desc.set(g[1] + ' ' + p, g[3].replace(/([A-Z])/g, ' $1').toLowerCase()); } }
for (const k of [...found.keys()]) if (k.startsWith('ANY /api/gaming')) found.delete(k);
for (const k of [...found.keys()]) if (k.includes('/api/dev')) found.delete(k);
// Drop ANY rows when the same path also has a concrete method.
const rows = [...found.values()].filter((r) => r.m !== 'ANY' || ![...found.values()].some((x) => x.p === r.p && x.m !== 'ANY'));
rows.forEach((r) => { r.d = desc.get(r.m + ' ' + r.p) || ''; });
rows.sort((a, b) => a.p.localeCompare(b.p) || a.m.localeCompare(b.m));
const groups = {};
for (const r of rows) { const g = r.p.split('/')[2]; (groups[g] = groups[g] || []).push([r.m, r.p, r.d]); }
fs.writeFileSync(path.join(here, '../docs/d-api-data.js'), `/* Generated by tools/build-api.mjs — do not edit by hand. */\nwindow.API_ROUTES = ${JSON.stringify(groups)};\n`);
console.log('API:', rows.length, 'endpoints in', Object.keys(groups).length, 'groups');

// Role matrix from server/roleAccess.json: which roles have each page/feature hidden.
const access = JSON.parse(fs.readFileSync(path.join(root, 'server/roleAccess.json'), 'utf8'));
const roleRows = Object.entries(access).filter(([k]) => k !== 'default').map(([k, v]) => [k, v.enabled !== false, v.featureHidden || [], v.statsAllowed || []]);
fs.appendFileSync(path.join(here, '../docs/d-api-data.js'), `window.ROLE_ACCESS = ${JSON.stringify(roleRows)};\n`);
console.log('Roles:', roleRows.length, 'access keys');
