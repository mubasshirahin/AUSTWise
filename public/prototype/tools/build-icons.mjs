// Extracts lucide icon nodes from node_modules/lucide-react into prototype/icons.js
// Run: node public/prototype/tools/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
const dir = 'node_modules/lucide-react/dist/esm/icons';
const names = fs.readFileSync('public/prototype/tools/icon-list.txt', 'utf8').split(/\s+/).filter(Boolean);
const out = {}; const missing = [];
for (const n of names) {
  const f = path.join(dir, n + '.mjs');
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  const src = fs.readFileSync(f, 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\s*\n\s*const /);
  if (!m) { missing.push(n + '(fmt)'); continue; }
  const node = Function('return ' + m[1])();
  out[n] = node.map(([t, a]) => { const { key, ...rest } = a; return [t, rest]; });
}
fs.writeFileSync('public/prototype/icons.js', '/* Generated by tools/build-icons.mjs (lucide, ISC license) */\nwindow.ICONS=' + JSON.stringify(out) + ';\n');
console.log('icons', Object.keys(out).length, 'missing', missing.join(' '));
